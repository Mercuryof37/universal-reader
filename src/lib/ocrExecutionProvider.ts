/**
 * OCR 的推理后端（ONNX Runtime execution providers）。
 *
 * ═══════════════════════════════════════════════════════════════
 * 为什么默认**只用 wasm**，而不是让库自动优先 WebGPU
 * ═══════════════════════════════════════════════════════════════
 *
 * `ppu-paddle-ocr` 在 web 平台上的默认值是（`web/platform.web.js`）：
 *
 *   if (await isWebGpuAvailable()) return ["webgpu", "wasm"];
 *   return ["wasm"];
 *
 * 也就是**只要浏览器支持 WebGPU，就会优先用它推理**。
 *
 * 而用户实测到的故障是：识别第 1 页时**页面被浏览器回收**，
 * 而且带上了应用自己记录的诊断 —— 「刷新来源：不是应用发起的」
 * （三条刷新路径都没有记录）、「中断前最后走到：recognize（开始识别）」。
 * 也就是：画布渲染成功之后，**在第一次推理时进程就没了，且没有任何 JS 报错**。
 *
 * 这种「静默进程死亡」正是 GPU 侧的典型表现：WebGPU 要编译着色器、
 * 申请显存，驱动或 GPU 进程一旦出问题，整个渲染进程会被直接带走，
 * 页面上不会留下异常、也不会留下日志 —— 用户只看到「页面自己刷新了、结果全没了」。
 *
 * 相比之下 WASM 后端全程在 CPU 上跑：慢一些，但**不会因为显卡驱动把页面弄崩**，
 * 出错时也会正常抛异常（能显示成错误横幅，而不是静默消失）。
 *
 * 对一个「导入文档、点识别、等结果」的工具来说，**可预测比快更重要** ——
 * 崩一次就白等一场，而且用户完全不知道发生了什么。
 *
 * ═══════════════════════════════════════════════════════════════
 * 想用 WebGPU 怎么办
 * ═══════════════════════════════════════════════════════════════
 *
 * 设 `VITE_OCR_USE_WEBGPU=1` 即可开回 `['webgpu', 'wasm']`。
 * 如果你的机器上 WebGPU 稳定，它会明显更快；
 * 但若出现过「识别时页面突然刷新」，请把它去掉。
 */
export function resolveExecutionProviders(
  useWebGpu = import.meta.env.VITE_OCR_USE_WEBGPU,
): readonly string[] {
  const enabled = useWebGpu === '1' || useWebGpu === 'true';
  return enabled ? ['webgpu', 'wasm'] : ['wasm'];
}
